def _fmt_days(days: int | None) -> str:
    """Compact and fixed-width, so the column never collapses."""
    if days is None:
        return "  —"
    if days == 0:
        return "today"
    return f"{days}d"


def _plain_table(title: str) -> Table:
    """Borderless table — reads as a list, not a spreadsheet."""
    return Table(
        title=title,
        title_style="bold",
        title_justify="left",
        header_style="dim",
        box=box.SIMPLE_HEAD,
        pad_edge=False,
        show_edge=False,
    )


def _severity(days: int | None, threshold: int) -> str:
    if days is None:
        return "dim"
    if days >= threshold * 3:
        return "bold red"
    if days >= threshold:
        return "yellow"
    return "green"


def _truncate(text: str, width: int) -> str:
    text = " ".join(text.split())
    return text if len(text) <= width else text[: width - 1] + "…"


