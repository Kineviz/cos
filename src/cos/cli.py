@main.command("alert")
@click.option("--dry-run", is_flag=True, help="Show what would be sent, send nothing.")
def alert_cmd(dry_run: bool) -> None:
    """Page Wei if something broke, at most once a day per problem.

    Meant to run from the 15-minute refresh. Alerts on the ok->broken
    transition only: an unguarded version would send 96 messages a day for one
    unfixed problem, and a muted bot is worse than no monitoring because it
    looks like coverage.
    """
    from . import alerting

    if dry_run:
        from . import health as health_mod

        decision = alerting.decide(health_mod.run_all())
        msg = alerting.format_alert(decision)
        console.print(msg or "[dim]nothing worth sending[/dim]")
