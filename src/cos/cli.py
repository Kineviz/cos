def _require_setup() -> "Config":
    """Stop with directions instead of computing against defaults.

    On a machine with nothing configured, `cos brief` used to invent a
    ~/vault directory and write a file into it, against an empty principal.
    A first command on a fresh install should say what to do next, not
    guess.
    """
    cfg = Config.load()
    if not cfg.principal_addresses:
        console.print("[yellow]Not configured yet.[/yellow] Run "
                      "[bold]cos setup[/bold] — it lists each step and "
                      "checks it off as you go.")
        sys.exit(2)
    return cfg


@main.command()
def setup() -> None:
    """Where your install stands: every prerequisite, checked, with the fix.

    Safe to run at any time, from the first minute. Nothing here writes
    anything except .env (copied from the example, once, so there is a file
    to edit).
    """
    from pathlib import Path

    repo = Path(__file__).resolve().parents[2]
    env_file = repo / ".env"
    if not env_file.exists() and (repo / ".env.example").exists():
        env_file.write_text((repo / ".env.example").read_text())
        console.print(f"[green]✓[/green] created .env from .env.example — edit it next")

    cfg = Config.load()
    rows: list[tuple[bool, str, str]] = []

    rows.append((env_file.exists(), ".env exists",
                 "cp .env.example .env"))
    rows.append((bool(cfg.principal_addresses),
                 f"COS_PRINCIPAL_ADDRESSES set"
                 + (f" ({cfg.principal_addresses[0]})" if cfg.principal_addresses else ""),
                 "edit .env: your own email address(es), comma-separated"))

    oauth = Path.home() / ".config" / "cos" / "oauth_client.json"
    from .google_auth import TOKEN_FILE as GOOGLE_TOKEN
    from .ms_auth import TOKEN_FILE as MS_TOKEN
    has_google = GOOGLE_TOKEN.exists()
    has_ms = MS_TOKEN.exists()
    rows.append((oauth.exists() or has_google or has_ms,
                 "a mail connection is prepared",
                 "Gmail: save the OAuth client JSON to "
                 "~/.config/cos/oauth_client.json (README step 2). "
                 "Microsoft: see docs/SETUP-MICROSOFT.md"))
    rows.append((has_google or has_ms,
                 "signed in to mail ("
                 + ("Gmail" if has_google else "Microsoft" if has_ms else "none")
                 + ")",
                 "Gmail: cos check (first run opens the consent screen). "
                 "Microsoft: cos ms-auth"))

    rows.append((cfg.vault_root.is_dir(),
                 f"notes folder exists ({cfg.vault_root})",
                 "optional — set COS_VAULT_ROOT in .env to your Obsidian "
                 "vault, or leave unset to skip notes"))
    rows.append(((repo / "config" / "deal_domains.yaml").exists(),
                 "deal list exists (config/deal_domains.yaml)",
                 "optional — cp config/deal_domains.example.yaml "
                 "config/deal_domains.yaml and add your deals"))

    ok = True
    for good, label, fix in rows:
        mark = "[green]✓[/green]" if good else "[red]✗[/red]"
        console.print(f"{mark} {label}")
        if not good:
            ok = False
            console.print(f"    → {fix}")

    console.print()
    if ok:
        console.print("[green]Ready.[/green] Try: [bold]cos brief[/bold], "
                      "then [bold]cos owed[/bold]. Dashboard: cos serve. "
                      "Brain + assistant: docs/SETUP-gbrain-hermes.md")
    else:
        console.print("Fix the [red]✗[/red] lines top to bottom, then run "
                      "[bold]cos setup[/bold] again.")
        sys.exit(1)


@main.command()
def check() -> None:
    """Verify the graph is reachable and current."""
    cfg = Config.load()
    with open_backend(cfg) as client:
        if not client.health():
            if getattr(client, "is_gmail", False):
                console.print("[red]✗[/red] Gmail unreachable — run `cos google-auth`")
            else:
                console.print(f"[red]✗[/red] Kuzu server unreachable at {cfg.kuzu_url}")
                console.print(
                    "  Start it:  cd $COS_GMAIL_ROOT && python scripts/serve.py --port 7001"
                )
            sys.exit(1)
        newest = corpus_freshness(client)
        console.print(f"[green]✓[/green] Mail source: {client.describe()}"
                      if getattr(client, "is_gmail", False)
                      else f"[green]✓[/green] Kuzu reachable at {cfg.kuzu_url}")
        console.print(f"  Newest message: {newest.astimezone():%Y-%m-%d %H:%M %Z}" if newest else "  empty graph")
        console.print(f"  Principal: {', '.join(cfg.principal_addresses)}")
        console.print(f"  Vault: {cfg.vault_root}")
        deals = load_deals(cfg.vault_root)
        console.print(f"  Deals found in vault: {len(deals)}")


@main.command()
@click.option("--days", type=int, default=None, help="Quiet threshold in days.")
@click.option("--all", "show_all", is_flag=True, help="Include deals under threshold.")
def quiet(days: int | None, show_all: bool) -> None:
    """Named deals with no human contact recently."""
    cfg = _require_setup()
    threshold = days if days is not None else cfg.quiet_days
    now = utc_now()

    deals = load_deals(cfg.vault_root)
    if not deals:
        console.print(
            "[yellow]No deals found.[/yellow] Expected an '## At a glance' table in "
            f"{cfg.vault_root}/05_workspace/Task_management/Pipeline.md"
        )
        return
    attach_domains(deals, load_deal_domains(cfg.deal_domains_path))

    try:
        with open_backend(cfg) as client:
            _freshness_warning(client, now)
            statuses = deal_status(deals, _build(cfg, client, now), now)
    except KuzuError as exc:
        console.print(f"[red]{exc}[/red]")
        sys.exit(1)

    flagged = [s for s in statuses if s.mapped and (show_all or (s.days_quiet(now) or 0) >= threshold)]
    unmapped = [s for s in statuses if not s.mapped]

    if not flagged:
        console.print(
            f"[green]Nothing quiet.[/green] All {len(statuses) - len(unmapped)} mapped "
            f"deals had human contact within {threshold} days."
        )
    else:
        table = _plain_table(f"Deals quiet ≥ {threshold} days  ·  {now.astimezone():%Y-%m-%d}")
        table.add_column("Quiet", justify="right", no_wrap=True, min_width=6)
        table.add_column("Deal", no_wrap=True, min_width=22)
        table.add_column("Ball", no_wrap=True, min_width=6)
        table.add_column("Stated next step", no_wrap=True, min_width=38)
        for s in flagged:
            d = s.days_quiet(now)
            table.add_row(
                f"[{_severity(d, threshold)}]{_fmt_days(d)}[/]",
                _truncate(s.deal.name, 22),
                "[yellow]yours[/yellow]" if s.ball_in_our_court() else "[dim]theirs[/dim]",
                _truncate(s.deal.next_step or "—", 38),
            )
        console.print(table)

    if unmapped:
        console.print(
            f"\n[dim]{len(unmapped)} deal(s) have no email domain mapped and were not "
            f"checked: {', '.join(s.deal.name for s in unmapped)}.\n"
            f"Add them to config/deal_domains.yaml.[/dim]"
        )


@main.command()
@click.option("--days", type=int, default=None, help="Only mail newer than this.")
@click.option("--limit", type=int, default=25, help="Max rows.")
@click.option(
    "--include-new",
    is_flag=True,
    help="Also show people you have never written to (noisier).",
)
def owed(days: int | None, limit: int, include_new: bool) -> None:
    """People who wrote last and have had no reply from you."""
    cfg = _require_setup()
    window = days if days is not None else cfg.owed_window_days
    now = utc_now()

    try:
        with open_backend(cfg) as client:
            _freshness_warning(client, now)
            ledger = _build(cfg, client, now)
    except KuzuError as exc:
        console.print(f"[red]{exc}[/red]")
        sys.exit(1)

    internal = load_internal_domains(cfg.deal_domains_path)
    items = owed_replies(
        ledger,
        now,
        window,
        internal_domains=internal,
        require_prior_reply=not include_new,
    )

    if not items:
        console.print(
            f"[green]Inbox conscience clear.[/green] Nobody outside "
            f"{', '.join(sorted(internal)) or 'your org'} is waiting on you "
            f"within the last {window} days."
        )
        return

    table = _plain_table(f"Waiting on you  ·  {now.astimezone():%Y-%m-%d}")
    table.add_column("Wait", justify="right", no_wrap=True, min_width=5)
    table.add_column("Who", no_wrap=True, min_width=22)
    table.add_column("Org", no_wrap=True, min_width=20)
    table.add_column("Their last message", no_wrap=True, min_width=38)
    for item in items[:limit]:
        table.add_row(
            f"[{_severity(item.days_waiting, 7)}]{_fmt_days(item.days_waiting)}[/]",
            _truncate(item.who, 22),
            _truncate(item.counterparty.domain, 20),
            _truncate(item.subject, 38),
        )
    console.print(table)
    console.print(
        f"[dim]{len(items)} waiting; showing {min(limit, len(items))}. "
        f"Counterparty-level, not thread-level — see README.[/dim]"
    )


@main.command()
@click.option(
    "--path", type=click.Path(path_type=Path), default=None,
    help="Dashboard file (default: 05_workspace/Task_management/Dashboard.md).",
)
def dashboard(path: Path | None) -> None:
    """Update the dashboard, preserving everything you have written in it."""
    cfg = _require_setup()
    now = utc_now()
    target = path or (
        cfg.vault_root / "05_workspace" / "Task_management" / "Dashboard.md"
    )
    deals = load_deals(cfg.vault_root)
    attach_domains(deals, load_deal_domains(cfg.deal_domains_path))
    try:
        with open_backend(cfg) as client:
            _freshness_warning(client, now)
            ledger = _build(cfg, client, now)
    except KuzuError as exc:
        console.print(f"[red]{exc}[/red]")
        sys.exit(1)

    statuses = deal_status(deals, ledger, now)
    owed = owed_replies(
        ledger, now, cfg.owed_window_days,
        internal_domains=load_internal_domains(cfg.deal_domains_path),
    )
    existing = target.read_text(encoding="utf-8") if target.is_file() else None
    body, rescued = dashboard_page.render(now, statuses, owed, cfg.quiet_days, existing)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(body, encoding="utf-8")

    # Index whatever the user has written, with the computed state at the time.
    ctx = {
        f"deal:{dashboard_page._slug(s.deal.name)}": {
            "quiet_days": s.days_quiet(now),
            "ball_with": "you" if s.ball_in_our_court() else "them",
            "stage": s.deal.stage,
        }
        for s in statuses
    }
    conn = notes_store.connect(cfg.notes_db)
    nstats = notes_store.sync(conn, notes_store.extract_from_dashboard(body), now, ctx)
    titles = {f"deal:{dashboard_page._slug(s.deal.name)}": s.deal.name for s in statuses}
    titles["journal"] = "General"
    # Link each notes page at the org card and any mapped domain, so gbrain's
    # graph-adjacency boost lifts a four-line page out of the shadow of the
    # thousand-word wiki pages it competes with.
    note_links: dict[str, list[str]] = {}
    for s_ in statuses:
        key = f"deal:{dashboard_page._slug(s_.deal.name)}"
        note_links[key] = [
            f"org-{dashboard_page._slug(d)}" for d in (s_.deal.domains or [])
        ]
    n_pages = notes_store.export_pages(
        conn, cfg.vault_root / "90_agent" / "Notes", titles, note_links,
    )

    console.print(f"[green]✓[/green] {target}")
    console.print(
        f"  {len([s for s in statuses if s.mapped])} deal(s) · {len(owed)} awaiting reply"
        + ("  [dim](created)[/dim]" if existing is None else "  [dim](updated in place)[/dim]")
    )
    if any(nstats[k] for k in ("new", "removed", "restored")):
        bits = [f"{nstats['new']} new" if nstats["new"] else "",
                f"{nstats['removed']} removed" if nstats["removed"] else "",
                f"{nstats['restored']} restored" if nstats["restored"] else ""]
        console.print(
            f"  [dim]notes: {', '.join(b for b in bits if b)} "
            f"({nstats['still_there'] + nstats['new']} tracked, "
            f"{n_pages} brain page(s))[/dim]"
        )
    if rescued:
        console.print(
            f"[yellow]  Moved your text out of {len(rescued)} computed block(s) "
            f"into the notes beneath: {', '.join(rescued)}[/yellow]"
        )


@main.command("note")
@click.argument("text", nargs=-1, required=True)
@click.option("--about", default=None, help="Entity, e.g. northwind, hillcrest, or a person.")
def note_cmd(text: tuple[str, ...], about: str | None) -> None:
    """Record something that exists nowhere else — a call, a hallway remark."""
    cfg = Config.load()
    now = utc_now()
    body = " ".join(text).strip()
    if not body:
        console.print("[red]Nothing to record.[/red]")
        sys.exit(1)

    entity = f"deal:{dashboard_page._slug(about)}" if about else "journal"

    # Markdown is the home; the DB is an index over it. Append first so a
    # database failure can never lose what you wrote.
    journal = cfg.vault_root / "05_workspace" / "Task_management" / "Kiran-Log.md"
    journal.parent.mkdir(parents=True, exist_ok=True)
    if not journal.exists():
        journal.write_text(
            "# Kiran Log\n\n> Things told to Kiran that are in no email and no "
            "note — calls, hallway remarks, judgement. Append-only; Kiran indexes "
            "it but never rewrites it.\n",
            encoding="utf-8",
        )
    with journal.open("a", encoding="utf-8") as fh:
        tag = f" · about **{about}**" if about else ""
        fh.write(f"\n## {now.astimezone():%Y-%m-%d %H:%M}{tag}\n\n- {body}\n")

    conn = notes_store.connect(cfg.notes_db)
    fresh = notes_store.add(conn, notes_store.Note(entity, body, source="cli"), now)
    notes_store.export_pages(conn, cfg.vault_root / "90_agent" / "Notes")
    console.print(
        f"[green]✓[/green] recorded{' about ' + about if about else ''} → {journal}"
        + ("" if fresh else "  [dim](already knew this one)[/dim]")
    )


@main.command("notes")
@click.option("--about", default=None, help="Filter by entity substring.")
@click.option("--all", "show_all", is_flag=True, help="Include notes you deleted.")
@click.option("--limit", type=int, default=30)
@click.option("--reindex", is_flag=True, help="Rebuild the index from the markdown.")
def notes_cmd(about: str | None, show_all: bool, limit: int, reindex: bool) -> None:
    """What you have told Kiran, and when."""
    cfg = Config.load()
    conn = notes_store.connect(cfg.notes_db)
    if reindex:
        tm = cfg.vault_root / "05_workspace" / "Task_management"
        dash = (tm / "Dashboard.md").read_text(encoding="utf-8") if (tm / "Dashboard.md").is_file() else ""
        log = (tm / "Kiran-Log.md").read_text(encoding="utf-8") if (tm / "Kiran-Log.md").is_file() else ""
        r = notes_store.reindex(conn, dash, log, utc_now())
        console.print(
            f"[green]✓[/green] rebuilt from markdown: {r['dashboard']} from Dashboard.md, "
            f"{r['log']} from Kiran-Log.md"
        )
    rows = notes_store.query(conn, about, include_removed=show_all, limit=limit)
    if not rows:
        console.print("[yellow]No notes recorded yet.[/yellow]  Try: cos note --about hillcrest \"...\"")
        return
    table = _plain_table(f"Notes{f' · {about}' if about else ''}")
    table.add_column("Written", no_wrap=True, min_width=10)
    table.add_column("About", no_wrap=True, min_width=16)
    table.add_column("Note", no_wrap=True, min_width=46)
    table.add_column("At the time", no_wrap=True, min_width=14)
    for r in rows:
        ctx = ""
        if r["context"]:
            try:
                import json as _j
                d = _j.loads(r["context"]) or {}
                if d.get("quiet_days") is not None:
                    ctx = f"quiet {d['quiet_days']}d, ball {d.get('ball_with','?')}"
            except Exception:
                pass
        label = r["entity"].replace("deal:", "")
        text = _truncate(r["text"], 46)
        if r["removed_at"]:
            text = f"[dim strike]{text}[/]"
        table.add_row(r["first_seen"][:10], _truncate(label, 16), text, ctx)
    console.print(table)
    s = notes_store.stats(conn)
    console.print(
        f"[dim]{s.get('live') or 0} live, {s.get('removed') or 0} deleted, "
        f"across {s.get('entities') or 0} entities since {(s.get('earliest') or '')[:10]}[/dim]"
    )


