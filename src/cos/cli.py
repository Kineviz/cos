SOUL_BEGIN = "<!-- cos:begin DATE -->"
SOUL_END = "<!-- cos:end DATE -->"
# The block already sitting in an existing SOUL.md carries the pre-rename
# marker. Matching only the current spelling would find no block, append a
# second one, and leave the old date above it — so the agent would load two
# contradictory "Today is" lines, with the stale one first. That is precisely
# the failure this whole mechanism exists to prevent.
_SOUL_BLOCK_RE = re.compile(
    rf"<!--\s*(?:cos|{compat.LEGACY_DIRNAME}):begin\s+DATE\s*-->"
    rf".*?"
    rf"<!--\s*(?:cos|{compat.LEGACY_DIRNAME}):end\s+DATE\s*-->",
    re.DOTALL,
)


def _stamp_soul_date(now, upcoming) -> bool:
    """Write today's date into the agent's system prompt.

    Kiran kept answering "what do I have tomorrow" from a two-month-old email
    whose subject read "meeting tomorrow". Retrieval can always lose to a better
    lexical match, so the date must not depend on retrieval at all — SOUL.md is
    loaded as the agent identity, ahead of any search, and cannot be outvoted.

    Managed block only: everything Wei wrote in SOUL.md is preserved.
    """
    soul = Path.home() / ".hermes" / "SOUL.md"
    if not soul.exists():
        return False
    local = now.astimezone()
    lines = [
        SOUL_BEGIN,
        f"**Today is {local:%A %d %B %Y} ({local:%Y-%m-%d}).** This line is "
        f"regenerated by `cos brief`; trust it over any date you infer from a "
        f"document, and never take a date from an email subject as \"today\".",
    ]
    if upcoming:
        today = [e for e in upcoming if e.start.astimezone().date() == local.date()]
        tmrw = [e for e in upcoming
                if (e.start.astimezone().date() - local.date()).days == 1]
        for label, group in (("Today", today), ("Tomorrow", tmrw)):
            if group:
                items = "; ".join(
                    f"{e.start.astimezone():%H:%M} {e.summary}"
                    + ("" if e.status == "confirmed" else f" [{e.status}]")
                    for e in group[:8]
                )
                lines.append(f"- **{label}:** {items}")
    lines.append(
        "Fuller detail, including attendees and who is waiting on a reply, is in "
        "`90_agent/today.md`."
    )
    lines.append(SOUL_END)
    block = "\n".join(lines)

    text = soul.read_text(encoding="utf-8")
    # Replace the first block and DELETE any others. Not just the first: the
    # rename briefly left two blocks in this file, an old-marker one above a
    # new-marker one, and a count=1 substitution would have refreshed the top
    # one forever while the stale copy sat below it permanently. Collapsing to
    # exactly one is the only state that cannot drift.
    seen = 0

    def _replace(_m: re.Match) -> str:
        nonlocal seen
        seen += 1
        return block if seen == 1 else ""

    text = _SOUL_BLOCK_RE.sub(_replace, text)
    if not seen:
        text = text.rstrip() + "\n\n" + block + "\n"
    # Collapse the blank lines a deleted duplicate leaves behind.
    text = re.sub(r"\n{3,}", "\n\n", text)
    soul.write_text(text, encoding="utf-8")
    return True


def _upcoming_meetings(cfg, now, days: int = 7, limit: int = 25):
    """The next week of meetings, or nothing if calendar is not connected.

    Deliberately best-effort: `cos brief` must still produce a date anchor on
    a machine with no Google grant, so a calendar failure degrades the page
    rather than the command.
    """
    try:
        from .calendar_source import load_events, is_worth_a_page
    except ImportError:
        return []
    try:
        principals = {p.lower() for p in cfg.principal_addresses}
        events = load_events(days_back=0, days_forward=days, now=now)
        upcoming = [
            e for e in events
            if e.start >= now and is_worth_a_page(e, principals)[0]
        ]
        upcoming.sort(key=lambda e: e.start)
        return upcoming[:limit]
    except Exception:
        return []


def _freshness_warning(client: KuzuClient, now: datetime) -> None:
    newest = corpus_freshness(client)
    if newest is None:
        return
    lag = (now - newest).days
    if lag > 2:
        console.print(
            f"[yellow]⚠ The mail graph's newest message is {lag} days old "
            f"({newest.astimezone():%Y-%m-%d}). Results are stale — check that mbsync "
            f"and the "
            f"scheduled Kuzu rebuild are running.[/yellow]\n"
        )


